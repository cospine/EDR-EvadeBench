// Read the offset of OXIDEntry._moxid
//
#define IPID_OFFSET_LEGACY 0x30
#define MOXID_OFFSET_LEGACY 0x18

#define IPID_OFFSET_CURRENT 0xb8
#define MOXID_OFFSET_CURRENT 0xc8

//
// Check if a pointer looks like a valid user-mode address.
//
static bool is_valid_user_ptr(PVOID p) {
    ULONG64 addr = (ULONG64)p;
    return addr > 0x10000 && addr < 0x00007FFFFFFFFFFFULL;
}

bool
find_oxid_offset(COM_CONTEXT* c) {
    PBYTE base_addr = c->base + c->ipid_tbl;

    //
    // Dump raw bytes at ipid_tbl.
    //
    printf("[*] ipid_tbl @ .data+0x%lX:\n    ", c->ipid_tbl);
    for (DWORD i = 0; i < 0x60; i++) {
        printf("%02X ", base_addr[i]);
        if ((i + 1) % 16 == 0) printf("\n    ");
    }
    printf("\n");

    //
    // Find pPageListStart: scan for a pointer that points to an array of combase pointers.
    //
    PBYTE pPageListStart = NULL;
    for (UINT ofs = 0; ofs < 0x50; ofs += 8) {
        PBYTE candidate = *(PBYTE*)(base_addr + ofs);
        if (!is_valid_user_ptr(candidate)) continue;

        // Try to read first entry from this candidate array (check if page0 pointer is valid)
        PBYTE page0 = NULL;
        if (!IsBadReadPtr(candidate, sizeof(PBYTE))) {
            page0 = *(PBYTE*)candidate;
        }
        if (!page0) continue;

        if (is_valid_user_ptr(page0)) {
            pPageListStart = candidate;
            printf("[*] pPageListStart at +0x%02X = %p -> page0 = %p\n", ofs, pPageListStart, page0);
            break;
        }
    }

    if (!pPageListStart) {
        printf("[!] Cannot find valid pPageListStart.\n");
        return false;
    }

    PBYTE page0 = *(PBYTE*)pPageListStart;
    printf("[*] Page 0 at %p\n", page0);

    //
    // Determine cbPerEntry: try multiple offsets.
    //
    ULONG64 cbPerEntry = 0;
    static const UINT cbOffsets[] = { 0x38, 0x40, 0x48, 0x30, 0x3C, 0x44 };
    for (int k = 0; k < (int)(sizeof(cbOffsets) / sizeof(cbOffsets[0])); k++) {
        ULONG64 v = *(ULONG64*)(base_addr + cbOffsets[k]);
        if (v >= 0x70 && v <= 0x200) {
            cbPerEntry = v;
            printf("[*] cbPerEntry = %llu (0x%llX) at +0x%02X\n", v, v, cbOffsets[k]);
            break;
        }
    }
    if (!cbPerEntry) { cbPerEntry = 0x80; printf("[*] cbPerEntry guessing 0x80\n"); }

    //
    // cEntriesPerPage: try multiple offsets.
    //
    USHORT cEntriesPerPage = 0;
    static const UINT cepOffsets[] = { 0x40, 0x42, 0x44, 0x48, 0x38, 0x3A };
    for (int k = 0; k < (int)(sizeof(cepOffsets) / sizeof(cepOffsets[0])); k++) {
        USHORT v = *(USHORT*)(base_addr + cepOffsets[k]);
        if (v > 0 && v <= 200) {
            cEntriesPerPage = v;
            printf("[*] cEntriesPerPage = %hu at +0x%02X\n", v, cepOffsets[k]);
            break;
        }
    }
    if (!cEntriesPerPage) cEntriesPerPage = 50;

    //
    // Dump first 0x80 bytes of entry #0.
    //
    printf("[*] Entry #0 raw:\n    ");
    for (int i = 0; i < 0x80; i++) {
        printf("%02X ", page0[i]);
        if ((i + 1) % 16 == 0) printf("\n    ");
    }
    printf("\n");

    //
    // Iterate entries to find one with valid pOXIDEntry + IPID + OXIDEntry match.
    //
    for (USHORT n = 0; n < cEntriesPerPage; n++) {
        PBYTE raw_entry = page0 + (n * cbPerEntry);

        // Find pOXIDEntry: any pointer into combase.
        PVOID pOXIDEntry = NULL;
        for (UINT ofs = 0; ofs + 8 <= cbPerEntry; ofs += 8) {
            PBYTE ptr = *(PBYTE*)(raw_entry + ofs);
            if (ptr >= c->base && ptr < c->base + 0x400000) {
                pOXIDEntry = ptr; // take the LAST valid pointer
            }
        }
        if (!pOXIDEntry) continue;

        // Find IPID: scan for a 16-byte blob that looks like {WORD offset, WORD page, WORD pid, WORD tid, BYTE seq[8]}.
        IPID ipid;
        bool found = false;
        for (UINT ofs = 0; ofs + 16 <= cbPerEntry; ofs += 2) {
            IPID* ip = (IPID*)(raw_entry + ofs);
            if (ip->offset < cEntriesPerPage && ip->page < 0x2000 &&
                ip->pid > 0 && ip->pid < 0x10000 && ip->tid > 0) {
                ipid = *ip;
                found = true;
                break;
            }
        }
        if (!found) continue;

        // Search for IPID within OXIDEntry.
        PBYTE buf = (PBYTE)pOXIDEntry;
        for (UINT ofs = 0; ofs < 256; ofs++) {
            if (!memcmp(&buf[ofs], &ipid, sizeof(IPID))) {
                if (ofs == IPID_OFFSET_LEGACY) {
                    c->oxid = MOXID_OFFSET_LEGACY;
                } else {
                    c->oxid = ofs + sizeof(IPID);
                }
                printf("[+] Entry #%d: IPID at OXIDEntry+0x%02X → MOXID at +0x%02X\n", n, ofs, c->oxid);
                return true;
            }
        }
    }
    return false;
}

//
// Read the offset of CIPIDTable::_palloc
//
bool
find_ipid_table(COM_CONTEXT* c) {
    PBYTE ds = (c->base + c->data);
    DWORD size = c->size;

    //
    // Known layout variants: { cb_ofs, pStart_ofs, pEnd_ofs, cep_ofs }
    // Win10: { 0x38, 0x08, 0x10, 0x40 }
    // Win11: { 0x48, 0x18, 0x20, 0x50 }  (from hex dump analysis)
    //
    struct Variant { UINT cb_ofs, ps_ofs, pe_ofs, cep_ofs; };
    static const Variant vars[] = {
        { 0x38, 0x08, 0x10, 0x40 },   // Win8/Win10
        { 0x48, 0x18, 0x20, 0x50 },   // Win11 24H2
        { 0x48, 0x10, 0x18, 0x50 },   // Win11 alt
    };

    for (int v = 0; v < (int)(sizeof(vars) / sizeof(vars[0])); v++) {
        const Variant& var = vars[v];
        UINT max_ofs = var.cep_ofs;
        if (var.cb_ofs > max_ofs) max_ofs = var.cb_ofs;
        if (var.ps_ofs > max_ofs) max_ofs = var.ps_ofs;
        if (var.pe_ofs > max_ofs) max_ofs = var.pe_ofs;

        for (DWORD i = 0; i < size - max_ofs - 8; i++) {
            USHORT cep = *(USHORT*)(ds + i + var.cep_ofs);
            if (cep != 0x32) continue;

            PBYTE base = ds + i;

            ULONG64 cb = *(ULONG64*)(base + var.cb_ofs);
            // Only accept known entry sizes: 0x70 (Win7), 0x78 (Win10), 0x80 (Win11)
            if (cb != 0x70 && cb != 0x78 && cb != 0x80 && cb != 0x88) continue;

            PBYTE ps = *(PBYTE*)(base + var.ps_ofs);
            PBYTE pe = *(PBYTE*)(base + var.pe_ofs);
            if (!is_valid_user_ptr(ps) || !is_valid_user_ptr(pe)) continue;
            if (pe <= ps) continue;

            // Page list size must be a multiple of pointer size and reasonable.
            ULONG64 page_cnt = (pe - ps) / sizeof(PBYTE);
            if (page_cnt == 0 || page_cnt > 5000) continue;

            // Verify page0 is readable and looks valid.
            PBYTE page0 = NULL;
            if (IsBadReadPtr(ps, sizeof(PBYTE))) continue;
            page0 = *(PBYTE*)ps;
            if (!is_valid_user_ptr(page0)) continue;

            // Verify page0 contents look like IPIDEntry data:
            // The first entry's pNextIPID (offset 0) should be 0 or a valid pointer.
            // Its pOXIDEntry (offset 0x28 or 0x30) should be a valid pointer.
            if (IsBadReadPtr(page0, cb)) continue;
            PBYTE pNext = *(PBYTE*)page0;
            if (pNext && !is_valid_user_ptr(pNext)) continue;

            // Check for a pOXIDEntry-like pointer at known offsets.
            bool has_oxid_ptr = false;
            static const UINT oxid_ofs[] = { 0x28, 0x30, 0x38 };
            for (int k = 0; k < (int)(sizeof(oxid_ofs) / sizeof(oxid_ofs[0])); k++) {
                if (oxid_ofs[k] + 8 > cb) continue;
                PBYTE ptr = *(PBYTE*)(page0 + oxid_ofs[k]);
                if (ptr && is_valid_user_ptr(ptr)) { has_oxid_ptr = true; break; }
            }
            if (!has_oxid_ptr) continue;

            c->ipid_tbl = i;
            printf("[*] IPID table at .data+0x%lX (%s): cbPerEntry=%llu, pages=%llu\n",
                   i, v == 0 ? "Win10" : "Win11", cb, page_cnt);
            return true;
        }
    }
    return false;
}

//
// Read everything from combase.dll or ole32.dll required to execute 
// IRundown::DoCallback() in a remote COM process.
//
bool
init_cc(COM_CONTEXT* ctx) {
    bool result = false;

    //
    // Get pointer to IMarshalEnvoy interface.
    //
    IMarshalEnvoy* e = NULL;
    HRESULT hr = CoGetObjectContext(IID_IMarshalEnvoy, (PVOID*)&e);

    if (FAILED(hr)) {
        printf("CoGetObjectContext(IID_IMarshalEnvoy) failed : %08lX\n", hr);
        return false;
    }

    //
    // Marshal the context header.
    // It should contain the secret GUID and heap address of server context.
    //
    IStream* s = SHCreateMemStream(NULL, 0);
    hr = e->MarshalEnvoy(s, MSHCTX_INPROC);

    if (FAILED(hr)) {
        printf("IMarshalEnvoy::MarshalEnvoy() failed : %08lX\n", hr);
        goto cleanup;
    }

    //
    // Read the context header into local buffer.
    //
    LARGE_INTEGER pos;
    pos.QuadPart = 0;
    hr = s->Seek(pos, STREAM_SEEK_SET, NULL);

    if (FAILED(hr)) {
        printf("IStream::Seek() failed : %08lX\n", hr);
        goto cleanup;
    }

    tagCONTEXTHEADER hdr;
    DWORD cbBuffer;
    hr = s->Read(&hdr, sizeof(hdr), &cbBuffer);

    if (FAILED(hr)) {
        printf("IStream::read(tagCONTEXTHEADER) failed : %08lX\n", hr);
        goto cleanup;
    }

    printf("Reading information about .data in combase.dll or ole32.dll\n");
    result = get_com_data(ctx);
    if (!result) goto cleanup;

    //
    // Locate g_pMTAEmptyCtx
    //
    printf("Searching for g_pMTAEmptyCtx\n");

    result = find_com_data(
        ctx,
        (PBYTE)&hdr.ByRefHdr.pServerCtx,
        sizeof(ULONG_PTR),
        &ctx->server_ctx
    );

    if (!result) goto cleanup;

    //
    // Locate CProcessSecret::s_guidOle32Secret
    //
    printf("Searching for CProcessSecret::s_guidOle32Secret\n");

    result = find_com_data(
        ctx,
        (PBYTE)&hdr.ByRefHdr.guidProcessSecret,
        sizeof(GUID),
        &ctx->secret
    );

    if (!result) goto cleanup;

    //
    // Locate CIPIDTable::_palloc and offset of OXID value.
    //
    printf("Searching for CIPIDTable::_palloc\n");

    result = find_ipid_table(ctx);
    if (!result) goto cleanup;

    //
    // Locate OXIDEntry._moxid
    //
    printf("Searching for OXIDEntry._moxid offset\n");
    result = find_oxid_offset(ctx);

cleanup:
    if (s) s->Release();
    if (e) e->Release();

    printf("Leaving. Status : %s\n", result ? "OK" : "FAILED");

    return result;
}

//
// Read IPID, OXID, and OID values from a COM process.
//
std::vector<IPID_ENTRY>
get_ipid_entries(PCOM_CONTEXT cc, HANDLE hp) {
    PVOID ipid_tbl = (cc->base + cc->ipid_tbl);

    CPageAllocator PageAllocator;
    std::vector<IPID_ENTRY> ipids;

    //
    // Read the CPageAllocator class
    //
    auto r = ReadProcessMemory(
        hp,
        ipid_tbl,
        &PageAllocator,
        sizeof(PageAllocator),
        NULL
    );

    //
    // This usually means the remote process has no COM.
    //
    if (!r) {
        //printf("ReadProcessMemory(PageAllocator) failed : %ld\n", GetLastError());
        return {};
    }

    //
    // Read the array of page addresses.
    //
    ULONG64 page_cnt = PageAllocator._pgalloc._cPages;
    std::vector<PULONG_PTR> pages(page_cnt);
    PVOID page_addr = PageAllocator._pgalloc._pPageListStart;

    r = ReadProcessMemory(
        hp,
        page_addr,
        pages.data(),
        page_cnt * sizeof(ULONG_PTR),
        NULL
    );

    if (!r) {
        printf("ReadProcessMemory(_pPageListStart) failed : %ld\n", GetLastError());
        return {};
    }

    //
    // For each page found.
    //
    for (ULONG64 i = 0; i < page_cnt; i++) {
        DWORD ipid_cnt = PageAllocator._pgalloc._cEntriesPerPage;
        std::vector<IPIDEntry> entries(ipid_cnt);

        //
        // Read array of IPID entries.
        //
        r = ReadProcessMemory(
            hp,
            (LPCVOID)pages[i],
            entries.data(),
            ipid_cnt * sizeof(IPIDEntry),
            NULL
        );

        if (!r) {
            printf("ReadProcessMemory(pages[%lld]) failed : %ld\n", i, GetLastError());
            continue;
        }

        //
        // For each IPID
        //
        for (DWORD j = 0; j < ipid_cnt; j++) {
            // skip inactive entries
            if (!entries[j].pOXIDEntry || !entries[j].dwFlags) continue;
            if (entries[j].dwFlags & (IPIDF_DISCONNECTED | IPIDF_DEACTIVATED)) continue;

            //
            // Only save IRundown?
            //
            if (!cc->verbose && entries[j].iid != IID_IRundown) continue;

            IPID_ENTRY ci = { 0 };

            ci.iid = entries[j].iid;
            ci.ipid = entries[j].ipid;

            PBYTE pOXIDEntry = (PBYTE)entries[j].pOXIDEntry;

            //
            // Read the _moxid value. (OXID and OID)
            //
            union {
                BYTE b[16];
                DWORD64 q[2];
            } tmp{ 0 };

            r = ReadProcessMemory(
                hp,
                (LPCVOID)(pOXIDEntry + cc->oxid),
                &tmp,
                sizeof(tmp),
                NULL
            );

            if (!r) {
                /**printf("ReadProcessMemory(pOXIDEntry._moxid=%p) failed : %ld\n",
                    (PVOID)(pOXIDEntry + cc->oxid),
                    GetLastError()
                    );*/
                continue;
            }

            ci.oxid = (OXID)tmp.q[0];
            ci.oid = (OID)tmp.q[1];

            // skip NULL OXID or OID entries
            if (!ci.oxid || !ci.oid) continue;

            ipids.push_back(ci);
        }
    }
    return ipids;
}

//
// Query information about a process token.
//
std::vector<BYTE>
QueryProcessTokenInformation(
    HANDLE                  hp,
    TOKEN_INFORMATION_CLASS cls)
{
    //
    // Open the process token.
    //
    HANDLE tkn;

    BOOL r = OpenProcessToken(
        hp,
        TOKEN_QUERY,
        &tkn
    );

    if (!r) return {};

    DWORD outlen = 0;

    //
    // Get the size of memory required for information.
    //
    r = GetTokenInformation(
        tkn,
        cls,
        NULL,
        0,
        &outlen);

    DWORD err = GetLastError();
    std::vector<BYTE> outbuf;

    if (err == ERROR_INSUFFICIENT_BUFFER ||
        err == ERROR_BAD_LENGTH) // TokenSessionId
    {
        outbuf.resize(outlen);

        GetTokenInformation(
            tkn,
            cls,
            outbuf.data(),
            outlen,
            &outlen
        );
    }
    CloseHandle(tkn);

    return outbuf;
}

//
// Return the Integrity Level (IL) of process.
//
const wchar_t*
GetProcessIL(HANDLE hp) {
    PTOKEN_MANDATORY_LABEL tml;
    std::vector<BYTE> outbuf;

    outbuf = QueryProcessTokenInformation(
        hp,
        TokenIntegrityLevel
    );

    if (outbuf.empty()) return L"Error";

    tml = (PTOKEN_MANDATORY_LABEL)outbuf.data();

    DWORD cnt = (DWORD)(UCHAR)(*GetSidSubAuthorityCount(tml->Label.Sid) - 1);
    DWORD level = *GetSidSubAuthority(tml->Label.Sid, cnt);

    if (level < SECURITY_MANDATORY_LOW_RID) return L"Untrusted";
    if (level < SECURITY_MANDATORY_MEDIUM_RID) return L"Low";
    if (level < SECURITY_MANDATORY_HIGH_RID) return L"Medium";
    if (level < SECURITY_MANDATORY_SYSTEM_RID) return L"High";
    if (level < SECURITY_MANDATORY_PROTECTED_PROCESS_RID) return L"System";

    return L"ProtectedProcess";
}

//
// Determine if process is elevated.
//
BOOL
IsProcessElevated(HANDLE hp) {
    PTOKEN_ELEVATION te;
    std::vector<BYTE> outbuf;

    outbuf = QueryProcessTokenInformation(
        hp,
        TokenElevation
    );
    if (outbuf.empty()) return FALSE;
    te = (PTOKEN_ELEVATION)outbuf.data();
    return te->TokenIsElevated;
}

//
// Return the user name of a process.
//
std::wstring
GetProcessUser(HANDLE hp) {
    PTOKEN_USER tu = NULL;
    std::vector<BYTE> outbuf;

    outbuf = QueryProcessTokenInformation(
        hp,
        TokenUser
    );
    if (outbuf.empty()) return L"Error";

    tu = (PTOKEN_USER)outbuf.data();

    DWORD userLen = 0, domainLen = 0;
    SID_NAME_USE Snu;

    BOOL r = LookupAccountSidW(
        NULL,
        tu->User.Sid,
        NULL,
        &userLen,
        NULL,
        &domainLen,
        &Snu
    );

    std::wstring user(userLen - 1, L'\0');
    std::wstring domain(domainLen - 1, L'\0');

    if (GetLastError() == ERROR_INSUFFICIENT_BUFFER) {
        r = LookupAccountSidW(
            NULL,
            tu->User.Sid,
            &user[0],
            &userLen,
            &domain[0],
            &domainLen,
            &Snu
        );

        if (r) {
            if (domainLen) {
                user = domain + L'\\' + user;
            }
        }
    }
    return user;
}

//
// List IPID entries for a process.
//
void
DumpIPID(PCOM_CONTEXT ctx, PPROCESSENTRY32 pe) {
    HANDLE hp = OpenProcess(
        PROCESS_VM_READ | PROCESS_QUERY_LIMITED_INFORMATION,
        FALSE,
        pe->th32ProcessID
    );

    if (!hp) {
        //printf("OpenProcess(%ld) failed : %ld\n", pe->th32ProcessID, GetLastError());
        return;
    }

    std::vector<IPID_ENTRY> entries = get_ipid_entries(ctx, hp);

    if (!entries.size()) {
        //printf("No IPID entries found.\n");
        goto leave;
    }

    printf("\n**************************************"
        "\nProcess  : %lS [%ld]"
        "\nUser     : %lS"
        "\nIL       : %lS"
        "\nElevated : %lS\n\n",
        pe->szExeFile,
        pe->th32ProcessID,
        GetProcessUser(hp).c_str(),
        GetProcessIL(hp),
        IsProcessElevated(hp) ? L"Yes" : L"No"
    );

    for (auto x : entries) {
        LPOLESTR iid = NULL;
        StringFromIID((const IID&)x.iid, &iid);

        LPOLESTR ipid = NULL;
        StringFromIID((const IID&)x.ipid, &ipid);

        LPOLESTR oxid = NULL;
        StringFromIID((const IID&)x.oxid, &oxid);

        std::wstring path = L"Interface\\" + std::wstring(iid);

        WCHAR iface[MAX_PATH + 1] = { 0 };
        DWORD len = MAX_PATH;

        LSTATUS lStatus = RegGetValueW(
            HKEY_CLASSES_ROOT,
            path.c_str(),
            NULL,
            RRF_RT_REG_SZ,
            NULL,
            iface,
            &len
        );

        if (lStatus == ERROR_SUCCESS) {
            printf("IPID:%lS,OXID:%lS : %lS\n",
                ipid ? ipid : L"N/A",
                oxid ? oxid : L"N/A",
                iface);
        }
        if (ipid) CoTaskMemFree(ipid);
        if (iid)  CoTaskMemFree(iid);
        if (oxid) CoTaskMemFree(oxid);
    }
leave:
    CloseHandle(hp);
}

//
// Enumerate IPID for all processes except our own.
//
void
ListIPID(PCOM_CONTEXT cc) {
    auto ss = CreateToolhelp32Snapshot(TH32CS_SNAPPROCESS, 0);

    if (ss == INVALID_HANDLE_VALUE) {
        printf("CreateToolhelp32Snapshot() failed : %ld\n", GetLastError());
        return;
    }

    PROCESSENTRY32 pe;
    pe.dwSize = sizeof(PROCESSENTRY32);

    if (Process32First(ss, &pe)) {
        do {
            if (pe.th32ProcessID <= 4 || pe.th32ProcessID == GetCurrentProcessId() ||
                (cc->pid && cc->pid != pe.th32ProcessID)) continue;

            //printf("Dumping %ld...\n", pe.th32ProcessID);
            DumpIPID(cc, &pe);
        } while (Process32Next(ss, &pe));
    }
    CloseHandle(ss);
}

