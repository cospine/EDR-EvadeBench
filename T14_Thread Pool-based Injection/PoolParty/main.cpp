// ============================================================
// AES-256-CBC decryption (Windows BCrypt API)
// Extract the IV from the payload (IV + ciphertext) and decrypt
// Returns 1 on success, 0 on failure
// ============================================================
int aes_decrypt_payload(
    const unsigned char* payload, int payload_len,
    unsigned char** output, int* output_len)
{
    BCRYPT_ALG_HANDLE  hAlg = NULL;
    BCRYPT_KEY_HANDLE  hKey = NULL;
    unsigned char* key_obj = NULL;
    unsigned char* iv_tmp = NULL;
    unsigned char* result = NULL;
    DWORD              key_obj_len = 0, block_len = 0;
    DWORD              data_len = 0, result_len = 0;
    NTSTATUS           status;
    int                ok = 0;

    *output = NULL;
    *output_len = 0;

    if (payload_len <= AES_IV_LEN) return 0;

    const unsigned char* iv = payload;
    const unsigned char* ciphertext = payload + AES_IV_LEN;
    int                  ct_len = payload_len - AES_IV_LEN;

    status = BCryptOpenAlgorithmProvider(&hAlg, BCRYPT_AES_ALGORITHM, NULL, 0);
    if (!NT_SUCCESS(status)) goto cleanup;

    status = BCryptSetProperty(hAlg, BCRYPT_CHAINING_MODE,
        (PUCHAR)BCRYPT_CHAIN_MODE_CBC, sizeof(BCRYPT_CHAIN_MODE_CBC), 0);
    if (!NT_SUCCESS(status)) goto cleanup;

    status = BCryptGetProperty(hAlg, BCRYPT_OBJECT_LENGTH,
        (PUCHAR)&key_obj_len, sizeof(DWORD), &data_len, 0);
    if (!NT_SUCCESS(status)) goto cleanup;

    status = BCryptGetProperty(hAlg, BCRYPT_BLOCK_LENGTH,
        (PUCHAR)&block_len, sizeof(DWORD), &data_len, 0);
    if (!NT_SUCCESS(status)) goto cleanup;

    key_obj = (unsigned char*)malloc(key_obj_len);
    iv_tmp = (unsigned char*)malloc(AES_IV_LEN);
    if (!key_obj || !iv_tmp) goto cleanup;

    status = BCryptGenerateSymmetricKey(hAlg, &hKey,
        key_obj, key_obj_len, (PUCHAR)AES_KEY, AES_KEY_LEN, 0);
    if (!NT_SUCCESS(status)) goto cleanup;

    memcpy(iv_tmp, iv, AES_IV_LEN);
    status = BCryptDecrypt(hKey, (PUCHAR)ciphertext, ct_len,
        NULL, iv_tmp, AES_IV_LEN, NULL, 0, &result_len, BCRYPT_BLOCK_PADDING);
    if (!NT_SUCCESS(status)) goto cleanup;

    result = (unsigned char*)malloc(result_len);
    if (!result) goto cleanup;

    memcpy(iv_tmp, iv, AES_IV_LEN);
    status = BCryptDecrypt(hKey, (PUCHAR)ciphertext, ct_len,
        NULL, iv_tmp, AES_IV_LEN, result, result_len, &data_len, BCRYPT_BLOCK_PADDING);
    if (!NT_SUCCESS(status)) goto cleanup;

    *output = result;
    *output_len = (int)data_len;
    result = NULL;
    ok = 1;

cleanup:
    if (!ok && result) free(result);
    if (hKey) BCryptDestroyKey(hKey);
    if (hAlg) BCryptCloseAlgorithmProvider(hAlg, 0);
    free(key_obj);
    free(iv_tmp);
    return ok;
}

